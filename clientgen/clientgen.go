// Package clientgen is the typed-client projection: it turns capability
// descriptors into Go source that calls those capabilities with typed
// inputs and outputs. The other projections serve a view to a caller that
// reads schemas while it runs (an agent, a script, an HTTP client); this
// one serves a compiled caller, which wants the schemas as types.
//
// The generated code imports only the standard library. It declares the
// one-method interface it calls through, so a generated client adds no
// module requirement to the program it is compiled into.
package clientgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"go/token"
	"slices"
	"sort"
	"strings"

	"github.com/craggy-io/capability-services/registry"
)

// Grouping is how the generated declarations are divided into files. It
// never changes a generated name.
type Grouping int

const (
	// OneFile puts everything in client.go.
	OneFile Grouping = iota
	// ByNamespace puts the Caller interface in client.go and each
	// namespace's capabilities (the first segment of their names) in
	// <namespace>_client.go.
	ByNamespace
)

// Options say what to generate.
type Options struct {
	// Package is the name of the generated Go package. Required.
	Package string
	// Include lists the capabilities to generate, each as name@version,
	// or as a bare name for the highest version described. A ref that no
	// descriptor has is an error. Empty means every descriptor.
	Include []string
	// Group divides the output into files.
	Group Grouping
}

// Header is the first line of every generated file.
const Header = "// Code generated by capability-services clientgen. DO NOT EDIT."

// ParseDescriptors reads descriptors that arrive as JSON: a list of
// descriptors, or an object with the list under "capabilities", which is
// the HTTP listing (GET /v1/) and the describe reply a provider process
// sends its host. Only the name, version, title, description, input,
// output and long members are used, so the wire form another process
// describes itself with is accepted as it is.
func ParseDescriptors(data []byte) ([]registry.Descriptor, error) {
	var list []registry.Descriptor
	var err error
	if trimmed := bytes.TrimSpace(data); len(trimmed) > 0 && trimmed[0] == '[' {
		err = json.Unmarshal(trimmed, &list)
	} else {
		var doc struct {
			Capabilities *[]registry.Descriptor `json:"capabilities"`
		}
		if err = json.Unmarshal(data, &doc); err == nil {
			if doc.Capabilities == nil {
				return nil, fmt.Errorf("clientgen: descriptors: no \"capabilities\" member")
			}
			list = *doc.Capabilities
		}
	}
	if err != nil {
		return nil, fmt.Errorf("clientgen: descriptors: %w", err)
	}
	for i, d := range list {
		if d.Name == "" {
			return nil, fmt.Errorf("clientgen: descriptors: entry %d has no name", i)
		}
	}
	return list, nil
}

// Generate returns the Go source of a client for the described
// capabilities, by file name. The files are formatted, start with Header,
// and depend only on the descriptors and the options: the same input
// gives the same bytes, in whatever order the descriptors are given.
// Nothing is written to disk.
//
// A Go name that would be derived twice is an error, never a rename; so
// is a schema that is not JSON.
func Generate(descriptors []registry.Descriptor, opts Options) (map[string][]byte, error) {
	if !token.IsIdentifier(opts.Package) || opts.Package == "_" {
		return nil, fmt.Errorf("clientgen: package name %q is not a Go identifier", opts.Package)
	}
	selected, err := selectDescriptors(descriptors, opts.Include)
	if err != nil {
		return nil, err
	}
	versions := map[string]int{}
	for _, d := range selected {
		versions[d.Name]++
	}
	g := &generator{names: map[string]string{}, structs: map[string][]field{}}
	files := map[string]*file{}
	fileOf := func(name string) *file {
		if files[name] == nil {
			files[name] = &file{}
		}
		return files[name]
	}
	base := fileOf("client.go")
	base.body.WriteString(callerSource)
	base.imports = map[string]bool{"bytes": true, "context": true, "encoding/json": true, "fmt": true}
	for _, d := range selected {
		f := base
		if opts.Group == ByNamespace {
			f = fileOf(goFile(namespaceOf(d.Name)))
		}
		if err := g.capability(f, d, versions[d.Name] > 1); err != nil {
			return nil, err
		}
	}
	out := map[string][]byte{}
	for name, f := range files {
		src, err := format.Source(f.source(opts.Package))
		if err != nil {
			return nil, fmt.Errorf("clientgen: %s: %w", name, err)
		}
		out[name] = src
	}
	return out, nil
}

// selectDescriptors picks the descriptors to generate, sorted by name
// and version.
func selectDescriptors(descriptors []registry.Descriptor, include []string) ([]registry.Descriptor, error) {
	byRef := map[string]registry.Descriptor{}
	highest := map[string]int{}
	for _, d := range descriptors {
		if d.Version <= 0 {
			d.Version = 1
		}
		d.Ref = fmt.Sprintf("%s@%d", d.Name, d.Version)
		if d.Name == "" || strings.Contains(d.Name, "@") {
			return nil, fmt.Errorf("clientgen: %q is not a capability name", d.Name)
		}
		if _, dup := byRef[d.Ref]; dup {
			return nil, fmt.Errorf("clientgen: %s is described twice", d.Ref)
		}
		byRef[d.Ref] = d
		highest[d.Name] = max(highest[d.Name], d.Version)
	}
	var selected []registry.Descriptor
	if len(include) == 0 {
		for _, d := range byRef {
			selected = append(selected, d)
		}
	}
	taken := map[string]bool{}
	for _, ref := range include {
		if !strings.Contains(ref, "@") {
			if v, ok := highest[ref]; ok {
				ref = fmt.Sprintf("%s@%d", ref, v)
			}
		}
		d, ok := byRef[ref]
		if !ok {
			return nil, fmt.Errorf("clientgen: no descriptor for %s", ref)
		}
		if !taken[ref] {
			taken[ref] = true
			selected = append(selected, d)
		}
	}
	sort.Slice(selected, func(i, j int) bool {
		if selected[i].Name != selected[j].Name {
			return selected[i].Name < selected[j].Name
		}
		return selected[i].Version < selected[j].Version
	})
	return selected, nil
}

// file is one generated file being written.
type file struct {
	imports map[string]bool
	body    strings.Builder
}

func (f *file) use(pkg string) {
	if f.imports == nil {
		f.imports = map[string]bool{}
	}
	f.imports[pkg] = true
}

func (f *file) source(pkg string) []byte {
	var b strings.Builder
	b.WriteString(Header + "\n\npackage " + pkg + "\n\n")
	var imports []string
	for path := range f.imports {
		imports = append(imports, path)
	}
	sort.Strings(imports)
	if len(imports) > 0 {
		b.WriteString("import (\n")
		for _, path := range imports {
			fmt.Fprintf(&b, "\t%q\n", path)
		}
		b.WriteString(")\n\n")
	}
	b.WriteString(f.body.String())
	return []byte(b.String())
}

// callerSource is what every generated package declares besides its
// capabilities.
const callerSource = `// Caller makes one capability call: it sends in, as JSON, to the
// capability ref names (name@version) and returns the capability's output
// as JSON. It waits for the capability to finish, however long that is,
// or for ctx to end. The functions in this package take whatever
// implements it: the handle a host gives a subsystem, an HTTP client, a
// registry in the same process, a fake in a test.
type Caller interface {
	Call(ctx context.Context, ref string, in any) (json.RawMessage, error)
}

// call makes one call and decodes its output into out. The Caller's error
// is returned as it is. A member the output has and out does not is
// ignored. A number that lands in an any is kept as a json.Number, so it
// is the number that was sent, however large.
func call(ctx context.Context, c Caller, ref string, in, out any) error {
	raw, err := c.Call(ctx, ref, in)
	if err != nil {
		return err
	}
	if len(bytes.TrimSpace(raw)) == 0 {
		return nil
	}
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	if err := dec.Decode(out); err != nil {
		return fmt.Errorf("%s: decoding the output: %w", ref, err)
	}
	return nil
}

`

type generator struct {
	names   map[string]string  // Go name -> what it was derived from
	structs map[string][]field // generated struct -> its fields
	decls   []*decl            // the type declarations of the capability being generated
}

// capability writes one capability: its ref, its input and output types,
// the function that calls it and, when it pages, the functions that read
// every page.
func (g *generator) capability(f *file, d registry.Descriptor, versioned bool) error {
	name := pascal(d.Name)
	if versioned {
		name += fmt.Sprintf("V%d", d.Version)
	}
	for _, n := range []string{name, name + "Ref"} {
		if err := g.declare(n, d.Ref); err != nil {
			return err
		}
	}
	g.decls = nil
	in, err := g.rootType(d, name+"In", "input", d.Input)
	if err != nil {
		return err
	}
	_, err = g.rootType(d, name+"Out", "output", d.Output)
	if err != nil {
		return err
	}

	b := &f.body
	fmt.Fprintf(b, "// %sRef is the capability %s calls.\nconst %sRef = %q\n\n", name, name, name, d.Ref)
	for _, decl := range g.decls {
		b.WriteString(decl.text)
		if decl.json {
			f.use("encoding/json")
		}
	}
	f.use("context")

	doc := name + " calls " + d.Ref
	if title := strings.TrimSpace(d.Title); title != "" {
		doc += ": " + strings.TrimSuffix(title, ".")
	}
	comment(b, "", doc+".")
	if desc := strings.TrimSpace(d.Description); desc != "" {
		comment(b, "", "\n"+desc)
	}
	if d.Long {
		comment(b, "", "\nThe capability is long-running. The call returns when it has finished, as the Caller does: there is no job handle to follow. End ctx to stop waiting.")
	}
	fmt.Fprintf(b, "func %s(ctx context.Context, c Caller, in %sIn) (%sOut, error) {\n", name, name, name)
	if in.kind == kindMap {
		// A nil map is null in JSON, which no object schema admits.
		fmt.Fprintf(b, "\tif in == nil {\n\t\tin = %sIn{}\n\t}\n", name)
	}
	fmt.Fprintf(b, "\tvar out %sOut\n\terr := call(ctx, c, %sRef, in, &out)\n\treturn out, err\n}\n\n", name, name)

	if p := g.paging(name+"In", name+"Out"); p != nil {
		for _, n := range []string{name + "Pages", name + "All"} {
			if err := g.declare(n, d.Ref+" paging"); err != nil {
				return err
			}
		}
		f.use("iter")
		if p.cursor {
			f.use("fmt")
		}
		b.WriteString(p.source(name, d.Ref))
	}
	return nil
}

// rootType declares the type of a capability's whole input or output and
// returns what it is. An object with properties is a struct; anything else
// is an alias of the Go type its schema maps to, and no schema at all is
// an empty struct for an input and json.RawMessage for an output.
func (g *generator) rootType(d registry.Descriptor, name, path string, raw json.RawMessage) (goType, error) {
	rt := &root{name: name, ref: d.Ref, path: path, defs: map[string]*defState{}}
	s, err := parseSchema(raw)
	if err != nil {
		return goType{}, fmt.Errorf("clientgen: %s schema: %w", rt.at(path), err)
	}
	if s == nil && path == "input" {
		s = &schema{types: []string{"object"}, hasProps: true}
	}
	rt.schema = s
	first := len(g.decls)
	t, err := g.typeOf(rt, s, name, path, false)
	if err != nil {
		return goType{}, err
	}
	if t.kind == kindStruct && strings.TrimPrefix(t.expr, "*") == name {
		return t, nil
	}
	if err := g.declare(name, rt.at(path)); err != nil {
		return goType{}, err
	}
	var b strings.Builder
	more := ""
	if t.kind == kindRaw {
		more = ", as JSON: its schema has no single Go type"
		if s == nil {
			more = ", as JSON: the capability declares no schema for it"
		}
	}
	typeDoc(&b, rt, s, name, path, more)
	fmt.Fprintf(&b, "type %s = %s\n\n", name, strings.TrimPrefix(t.expr, "*"))
	// The alias goes before the types it is made of.
	g.decls = slices.Insert(g.decls, first, &decl{text: b.String(), json: strings.Contains(t.expr, "json.RawMessage")})
	return t, nil
}
